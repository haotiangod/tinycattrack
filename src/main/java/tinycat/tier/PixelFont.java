    private PixelFont() {
    }

    private static void add(char c, String... rows) {
        GLYPHS.put(c, rows);
    }

    public static int textWidth(String text, int scale) {
        if (text == null || text.isEmpty()) {
            return 0;
        }
        return text.length() * 6 * scale - scale;
    }

    public static void drawText(Pixmap pixmap, String text, int x, int y, int scale, Color color) {
        if (text == null || text.isEmpty()) {
            return;
        }
        pixmap.setColor(color);
        int cursorX = x;
        for (int i = 0; i < text.length(); i++) {
            char c = Character.toUpperCase(text.charAt(i));
            String[] glyph = GLYPHS.get(c);
            if (glyph != null) {
                for (int row = 0; row < 7; row++) {
                    String line = glyph[row];
                    for (int col = 0; col < 5; col++) {
                        if (line.charAt(col) == '1') {
                            pixmap.fillRectangle(cursorX + col * scale, y + row * scale, scale, scale);
                        }
                    }
                }
            }
            cursorX += 6 * scale;
        }
    }

    public static void drawCentered(Pixmap pixmap, String text, int y, int scale, Color color) {
        int width = textWidth(text, scale);
        int x = (pixmap.getWidth() - width) / 2;
        drawText(pixmap, text, x, y, scale, color);
    }
